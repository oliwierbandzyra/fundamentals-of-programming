# Zapisujemy nazwę miasta 'Krakow' w zmiennej tekstowej city
city = 'Krakow'
# Pętla for przechodzi po kolei przez każdy pojedynczy znak (literę) w napisie city i zapisuje go w zmiennej char
for char in city:
    # Wypisujemy aktualną literę na ekranie (każda kolejna pojawi się w nowej linii)
    print(char)
