###
# A program that calculates the length of the diagonal
# of a rectangle with sides a and b.
#
import math # import funkcji math
a = 5
b = 8
diagonal = math.sqrt(a**2 + b**2) # stworzenie zmiennej "przekątna" która równa  jest pierwiastkowi kwadratowemu z a do kwadratu + b do kwadratu
print("Przekątna prostokąta wynosi:", diagonal)