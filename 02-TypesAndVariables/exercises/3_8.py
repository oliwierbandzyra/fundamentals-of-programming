###
# A program that calculates and prints
# the average grade of a student
#

# Przypisujemy oceny z poszczególnych przedmiotów liczbowo
math = 5
art = 4
music = 5
history = 3

# Sumowanie liczb i dzielenie w celu wyciągnięcia średniej artmetycznej
average = (math + art + music + history) / 4

# Poprawiono cudzysłów w funkcji print
print("Average grade is", average)