# Obliczanie średniej arytmetycznej liczb 7, 12 i 31 z dokładnością do 2 miejsc po przecinku
#
num1 = 7
num2 = 12
num3 = 31
mean_val = (num1 + num2 + num3) / 3  # dodanie zmieniej która dodaje zmienne z wartościami liczbowymi i podzielenie przez ich ilość
print("Średnia arytmetyczna:", round(mean_val, 2)) #zaokrąglenie zmiennej mean_val do dwóch miejsc po przecinku